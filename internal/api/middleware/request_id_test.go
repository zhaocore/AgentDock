package middleware

import (
	"net/http"
	"net/http/httptest"
	"testing"

	"github.com/gin-gonic/gin"
	"github.com/google/uuid"
)

func TestRequestID(t *testing.T) {
	gin.SetMode(gin.TestMode)
	r := gin.New()
	r.Use(RequestID())
	r.GET("/", func(c *gin.Context) {
		c.String(http.StatusOK, c.GetString(RequestIDKey))
	})
	first := httptest.NewRecorder()
	req := httptest.NewRequest(http.MethodGet, "/", nil)
	req.Header.Set("X-Request-ID", "client-supplied")
	r.ServeHTTP(first, req)
	second := httptest.NewRecorder()
	r.ServeHTTP(second, httptest.NewRequest(http.MethodGet, "/", nil))
	if _, err := uuid.Parse(first.Header().Get("X-Request-ID")); err != nil {
		t.Fatalf("invalid request ID: %v", err)
	}
	if first.Body.String() != first.Header().Get("X-Request-ID") || first.Body.String() == "client-supplied" {
		t.Fatalf("request ID not generated by server: %q", first.Body.String())
	}
	if second.Header().Get("X-Request-ID") == first.Header().Get("X-Request-ID") {
		t.Fatal("different requests share an ID")
	}
}
